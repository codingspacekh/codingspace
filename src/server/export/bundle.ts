import type { SupabaseClient } from '@supabase/supabase-js';
import { docToMarkdown } from './markdown';
import { zip, type ZipEntry } from './zip';

/**
 * Everything the site is made of, as one ZIP (03 ADM-16, NFR-REL-2):
 *   content.json             every row of every content table: the backup a restore reads
 *   posts/<subject>/<slug>.md  each post's latest version in content:import's format, to read
 *                            or move elsewhere (life posts under posts/life/)
 * Uploaded files themselves stay in R2; media rows point at them.
 */

// Parents before children, so a restore can insert in this order.
export const EXPORT_TABLES = [
  { name: 'subjects', order: 'id' },
  { name: 'sections', order: 'id' },
  { name: 'media', order: 'id' },
  { name: 'posts', order: 'id' },
  { name: 'post_revisions', order: 'id' },
  { name: 'post_media', order: 'post_id' },
  { name: 'projects', order: 'id' },
  { name: 'project_screenshots', order: 'project_id' },
  { name: 'profile', order: 'id' },
  { name: 'author_sections', order: 'id' },
  { name: 'author_items', order: 'id' },
  { name: 'featured_problems', order: 'id' },
  { name: 'series', order: 'id' },
  { name: 'series_lessons', order: 'series_id' },
  { name: 'syllabuses', order: 'id' },
  { name: 'syllabus_points', order: 'id' },
  { name: 'post_syllabus', order: 'post_id' },
] as const;

export type TableName = (typeof EXPORT_TABLES)[number]['name'];
type Row = Record<string, unknown>;
export type ExportData = {
  format: 1;
  exported_at: string;
  tables: Record<TableName, Row[]>;
  /** Tables left out to keep a download small enough (their rows are []). */
  omitted?: TableName[];
};

// Generated by the database from other columns: never exported, never restored.
const GENERATED: Partial<Record<TableName, string[]>> = { posts: ['live_search'] };
const PAGE = 1000;

export async function readContent(supabase: SupabaseClient, now = new Date()): Promise<ExportData> {
  const tables = {} as Record<TableName, Row[]>;
  for (const { name, order } of EXPORT_TABLES) {
    const rows: Row[] = [];
    for (let from = 0; ; from += PAGE) {
      const query = supabase
        .from(name)
        .select('*')
        .order(order)
        .range(from, from + PAGE - 1);
      const { data, error } = await (name === 'post_media'
        ? query.order('media_id')
        : name === 'post_syllabus'
          ? query.order('point_id')
          : name === 'series_lessons' || name === 'project_screenshots'
            ? query.order('position')
            : query);
      if (error) throw new Error(`${name}: ${error.message}`);
      rows.push(...(data as Row[]));
      if (data.length < PAGE) break;
    }
    for (const column of GENERATED[name] ?? []) for (const row of rows) delete row[column];
    tables[name] = rows;
  }
  return { format: 1, exported_at: now.toISOString(), tables };
}

const yaml = (v: unknown) => (typeof v === 'string' ? JSON.stringify(v) : String(v));

/** One post as content:import reads it, from the latest (draft) version. */
export function postMarkdown(post: Row, sections: Map<string, string>): ZipEntry {
  const lesson = post.kind === 'lesson';
  const meta: Record<string, unknown> = {
    title: post.title,
    summary: post.summary,
    section: lesson && post.section_id ? sections.get(String(post.section_id)) : undefined,
    sort: post.sort,
    level: lesson ? post.level : undefined,
    lang: post.lang,
    status: post.status,
    published_at: post.published_at,
  };
  const front = Object.entries(meta)
    .filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => `${k}: ${yaml(v)}`)
    .join('\n');
  const folder = post.kind === 'life' ? 'life' : String(post.subject_id);
  return { path: `posts/${folder}/${post.slug}.md`, data: `---\n${front}\n---\n\n${docToMarkdown(post.content_json)}` };
}

const README = (data: ExportData) => `# CodingSpace export

Made ${data.exported_at}.

- \`content.json\`: every row of every content table (posts with drafts, revisions, sections,
  media records, projects, the Author page and its sections, problems of the week). This is
  what a restore reads: see docs/runbook.md, "Restore from a backup".
- \`posts/<subject>/<slug>.md\`: each post's latest version as Markdown, in the format
  \`npm run content:import\` reads. Images, files and embeds are links.

Uploaded images and files are not inside: they stay in the R2 bucket, at the addresses the
media records and the Markdown links point to.
${
  data.omitted?.length
    ? `\nLeft out to keep this download small enough: ${data.omitted.join(', ')} (earlier versions of posts).
The weekly backup keeps them.\n`
    : ''
}`;

export function exportEntries(data: ExportData): ZipEntry[] {
  const sections = new Map(data.tables.sections.map((s) => [String(s.id), String(s.slug)]));
  return [
    { path: 'README.md', data: README(data) },
    { path: 'content.json', data: `${JSON.stringify(data, null, 2)}\n` },
    ...data.tables.posts.map((p) => postMarkdown(p, sections)),
  ];
}

/** Vercel answers at most 4.5 MB from a function; leave room for headers. */
export const DOWNLOAD_LIMIT = 4_000_000;

/**
 * The export as a ZIP and its file name, e.g. codingspace-export-2026-10-17.zip. Over
 * `maxBytes`, the revision history is left out (and the README says so).
 */
export async function exportZip(supabase: SupabaseClient, { now = new Date(), maxBytes = Infinity } = {}) {
  const data = await readContent(supabase, now);
  let body = zip(exportEntries(data), now);
  if (body.length > maxBytes && data.tables.post_revisions.length) {
    data.tables.post_revisions = [];
    data.omitted = ['post_revisions'];
    body = zip(exportEntries(data), now);
  }
  return {
    filename: `codingspace-export-${data.exported_at.slice(0, 10)}.zip`,
    body,
    counts: Object.fromEntries(Object.entries(data.tables).map(([k, v]) => [k, v.length])) as Record<TableName, number>,
    omitted: data.omitted ?? [],
  };
}
